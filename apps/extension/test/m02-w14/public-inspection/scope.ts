/** Reject redirects, sibling jobs, credentials, extra ports, query or fragments. */
export function permitsPublicDocumentUrl(value: string): boolean {
  try {
    const url = new URL(value);
    return (
      url.protocol === "https:" &&
      url.username === "" &&
      url.password === "" &&
      url.port === "" &&
      url.search === "" &&
      url.hash === "" &&
      approved.has(url.href)
    );
  } catch {
    return false;
  }
}
